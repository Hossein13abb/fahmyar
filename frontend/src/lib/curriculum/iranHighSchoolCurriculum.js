/**
 * درس‌های یک رشته و پایه.
 * @param {MajorType} major
 * @param {GradeType} grade
 * @returns {SubjectItem[]}
 */
export function getSubjects(major, grade) {
  return IRAN_CURRICULUM_DATA.filter(
    (s) => s.grade === String(grade) && s.majors.includes(major),
  )
}

/**
 * فصل‌های یک درس.
 * @param {string} subjectId
 * @returns {ChapterItem[]}
 */
export function getChapters(subjectId) {
  const subject = IRAN_CURRICULUM_DATA.find((s) => s.id === subjectId)
  return subject ? subject.chapters : []
}

/**
 * مفاهیمِ یک فصل.
 * @param {string} subjectId
 * @param {string} chapterId
 * @returns {ConceptItem[]}
 */
export function getConcepts(subjectId, chapterId) {
  const chapter = getChapters(subjectId).find((c) => c.id === chapterId)
  return chapter ? chapter.concepts : []
}

/**
 * اطلاعاتِ کاملِ یک مفهوم، برای فرستادن به API.
 *
 * @param {MajorType} major
 * @param {GradeType} grade
 * @param {string} subjectId
 * @param {string} chapterId
 * @param {string} conceptId
 * @returns {{
 *   major: MajorType, grade: GradeType,
 *   subjectId: string, subjectTitle: string,
 *   chapterNumber: number, chapterTitle: string,
 *   conceptId: string, conceptTitle: string,
 * } | null}
 */
export function resolveConcept(major, grade, subjectId, chapterId, conceptId) {
  const subject = IRAN_CURRICULUM_DATA.find((s) => s.id === subjectId)
  if (!subject) return null
  const chapter = subject.chapters.find((c) => c.id === chapterId)
  if (!chapter) return null
  const concept = chapter.concepts.find((c) => c.id === conceptId)
  if (!concept) return null
  return {
    major,
    grade: String(grade),
    subjectId: subject.id,
    subjectTitle: subject.title,
    chapterNumber: chapter.chapterNumber,
    chapterTitle: chapter.title,
    conceptId: concept.id,
    conceptTitle: concept.title,
  }
}

