"""واژگانِ عمومیِ محصول — سپرِ اصطلاحاتِ متدولوژیِ داخلی.

## چرا این فایل وجود دارد

روشِ سنجشِ فهم‌یار (زنجیرهٔ پنج‌مرحله‌ای) **داراییِ فکری** است. اسم‌های
داخلیِ مراحل — «لایهٔ نقاب»، «چالشِ فاینمن»، «ساعتِ خراب»، «مونتاژِ ذهنی» —
دو مشکل می‌سازند:

۱. **افشای متدولوژی.** هر کسی که یک کارنامه ببیند، نقشهٔ سنجش را می‌خواند.
۲. **بارِ شناختیِ بی‌مورد.** دانش‌آموز باید بفهمد «لایهٔ نقاب» یعنی چه،
   در حالی که فقط باید به سؤال جواب بدهد.

پس منطقِ ارزیابی دست نمی‌خورد (بک‌اند همان پنج تیپ را می‌سنجد)؛ فقط
**زبانِ رو به کاربر** عوض می‌شود.

## لایهٔ دوم — نشتیِ متنِ مدل

جلوگیری از برچسبِ ثابت کافی نیست. خودِ مدل هم این واژه‌ها را در خلاصه و
توضیح می‌نویسد (در کارنامهٔ واقعی دیدیم: «در ۵ مرحله لغزیدی: «فلسفه و
تصویر کلان» …»). پس هر متنی که از مدل می‌آید از :func:`scrub` می‌گذرد.

``scrub`` عمداً **محافظه‌کار** است: فقط عبارتِ چندکلمه‌ای را عوض می‌کند،
نه هر کلمهٔ تنها را — وگرنه «نقاب» در «نقابِ ابوالهول» یا «ساعت» در
«ساعتِ کلاس» هم عوض می‌شد و متن بی‌معنا می‌شد.
"""

