# ── واژه‌های ممنوعه در متنِ رو به کاربر ────────────────────────────────
# الگو → جایگزین. کلیدها عمداً **عبارتِ چندکلمه‌ای** هستند (به‌جز مواردی
# که خودِ کلمه در این محصول فقط معنای متدولوژیک دارد: «فاینمن»).
