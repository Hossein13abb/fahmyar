    # مرحله ۴
    (r"عیب‌یابیِ?\s*ساعتِ?\s*خراب(?:\s*\([^)]*\))?", "بررسی استدلال علمی"),
    (r"ساعتِ?\s*خراب", "استدلال نادرست"),
    (r"عیب‌یابیِ?\s*ساعت", "بررسی استدلال"),
    # مرحله ۵
    (r"چالشِ?\s*فاینمن(?:\s*\([^)]*\))?", "توضیح ساده و شهودی"),
    (r"فاینمن", "توضیح ساده"),
    (r"توضیح\s*با\s*دستِ?\s*بسته", "توضیح ساده"),
    # ── استعارهٔ ساعت و چرخ‌دنده (فاز ۱۹) ──
    # این استعاره در کارنامه جا افتاده بود و به زبانِ دانش‌آموز راه پیدا
    # کرده بود: «ساعت رو بستم»، «چرخ‌دندهٔ گمشده». مانعِ یادگیری است، چون
