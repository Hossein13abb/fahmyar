def scrub(text: Any) -> Any:
    """همهٔ اصطلاحاتِ متدولوژیِ داخلی را با زبانِ عمومی عوض می‌کند.

    ورودیِ غیرمتنی دست‌نخورده برمی‌گردد تا این تابع بی‌خطر باشد در جایی که
    مقدار ممکن است ``None`` یا عدد باشد.
    """
    if not isinstance(text, str) or not text:
        return text
    out = text
    for pattern, replacement in _COMPILED:
        out = pattern.sub(replacement, out)
    # فاصله‌های دوتایی و نقطه‌گذاریِ آویزان بعد از حذف
    out = re.sub(r"[ \t]{2,}", " ", out)
    out = re.sub(r"\s+([،.:؛])", r"\1", out)
    return out


def scrub_deep(value: Any) -> Any:
    """``scrub`` روی همهٔ رشته‌های یک ساختارِ تودرتو (dict/list)."""
    if isinstance(value, str):
        return scrub(value)
    if isinstance(value, list):
        return [scrub_deep(v) for v in value]
    if isinstance(value, dict):
        return {k: scrub_deep(v) for k, v in value.items()}
    return value


def public_stage_title(
    order: int, fallback: str = "سؤال تحلیلی", *, ten_question_scale: bool = True
) -> str:
    """برچسبِ عمومیِ مرحله از شمارهٔ ترتیب.

    دو مقیاس در محصول هست و نمی‌شود از عدد حدس زد کدام است:

    * آزمونِ جدید: ۱۰ سؤال، هر مرحله ۲ سؤال → ``ten_question_scale=True``
    * کارنامه‌های قدیمی: هر رکورد خودش یک مرحله → ``False``

    پیش‌تر حدس می‌زدم (`order > 5`) و همین باعث می‌شد سؤالِ ۲
    «سؤال چهارگزینه‌ای» برچسب بخورد. حالا صریح است.
    """
    n = int(order)
    stage = (n - 1) // 2 + 1 if ten_question_scale else n
    return PUBLIC_STAGE_TITLES.get(stage, fallback)
