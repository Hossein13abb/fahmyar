CLARIFIER_ADDENDUM = """
---
اطلاعاتِ تازه رسید: دانش‌آموز به سؤالِ بازپرسیِ تو پاسخ داده است.

پاسخِ او به بازپرسی:
{clarification_answer}

حالا حکمِ نهایی را صادر کن. اگر پاسخش نشان می‌دهد که بی‌دقتی بوده (Slip)،
در `evaluation_report.cross_check_findings` یک یافته از نوع `SLIP_RESOLVED`
اضافه کن و حکم را بر اساسِ فهمِ واقعی‌اش بده — نه بر اساسِ آن یک تست.
اگر تأیید کرد که واقعاً همان نظرِ متناقض را دارد، آن را کج‌فهمی (Misconception)
بشمار و صادقانه بگو.

`needs_clarification` این بار باید false باشد. خروجی فقط JSON معتبر باشد.
"""


def build_clarify_prompt(
    topic: str,
    blueprint: dict[str, Any],
    questions: list[dict[str, Any]],
    answers: dict[int, str],
    clarification_answer: str,
    previous_report: dict[str, Any] | None = None,
    signals: dict[str, Any] | None = None,
) -> str:
    base = build_evaluator_prompt(topic, blueprint, questions, answers, signals)
    parts = [base]
    if previous_report:
        parts.extend(
            [
                "",
                "---",
                "حکمِ قبلیِ تو (پیش از بازپرسی) — باید با آن سازگار بمانی یا صریحاً دلیلِ تغییر را بگویی:",
                json.dumps(previous_report, ensure_ascii=False, indent=2),
            ]
        )
    parts.append(CLARIFIER_ADDENDUM.format(clarification_answer=clarification_answer or "(بدون پاسخ)"))
    return "\n".join(parts)
